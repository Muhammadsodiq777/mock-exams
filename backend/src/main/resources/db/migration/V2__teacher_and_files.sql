create table files (
    id bigint generated by default as identity primary key,
    owner_user_id bigint,
    purpose varchar(40) not null,
    bucket varchar(120) not null,
    object_key varchar(500) not null unique,
    original_name varchar(255) not null,
    content_type varchar(120) not null,
    size_bytes bigint not null,
    duration_seconds integer,
    checksum varchar(128),
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_files_owner_user foreign key (owner_user_id) references users (id) on delete set null,
    constraint chk_files_purpose check (
        purpose in (
            'listening_audio',
            'speaking_audio',
            'teacher_avatar',
            'passage_image',
            'diagram',
            'document',
            'course_material',
            'banner_image'
        )
    ),
    constraint chk_files_size_non_negative check (size_bytes >= 0),
    constraint chk_files_duration_positive check (duration_seconds is null or duration_seconds > 0)
);

create table teacher_profiles (
    id bigint generated by default as identity primary key,
    user_id bigint not null unique,
    display_name varchar(160) not null,
    headline varchar(180),
    bio text,
    avatar_file_id bigint,
    status varchar(32) not null default 'draft',
    approved_by_user_id bigint,
    approved_at timestamp with time zone,
    rejection_reason text,
    rating_average numeric(3,2) not null default 0,
    rating_count integer not null default 0,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_teacher_profiles_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_teacher_profiles_avatar_file foreign key (avatar_file_id) references files (id) on delete set null,
    constraint fk_teacher_profiles_approved_by_user foreign key (approved_by_user_id) references users (id) on delete set null,
    constraint chk_teacher_profiles_status check (status in ('draft', 'pending_approval', 'approved', 'rejected', 'suspended')),
    constraint chk_teacher_profiles_rating_average check (rating_average >= 0 and rating_average <= 5),
    constraint chk_teacher_profiles_rating_count check (rating_count >= 0),
    constraint chk_teacher_profiles_approval_state check (
        (status = 'approved' and approved_by_user_id is not null and approved_at is not null)
        or status <> 'approved'
    )
);

create index idx_files_owner_purpose on files (owner_user_id, purpose);
create index idx_files_created_at on files (created_at);
create index idx_teacher_profiles_status_created_at on teacher_profiles (status, created_at);
create index idx_teacher_profiles_approved_at on teacher_profiles (approved_at);
create index idx_teacher_profiles_rating on teacher_profiles (rating_average, rating_count);
