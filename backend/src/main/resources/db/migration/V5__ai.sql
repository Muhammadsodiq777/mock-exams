create table ai_feedbacks (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    feedback_type varchar(24) not null,
    writing_submission_id bigint,
    speaking_submission_id bigint,
    status varchar(24) not null default 'queued',
    provider varchar(80),
    model varchar(120),
    prompt_tokens integer not null default 0,
    completion_tokens integer not null default 0,
    estimated_cost numeric(12,6) not null default 0,
    overall_band numeric(2,1),
    criteria_scores jsonb,
    mistakes jsonb,
    improved_answer text,
    action_plan jsonb,
    error_message text,
    created_at timestamp with time zone not null default current_timestamp,
    completed_at timestamp with time zone,
    constraint fk_ai_feedbacks_student_user foreign key (student_user_id) references users (id),
    constraint fk_ai_feedbacks_writing_submission foreign key (writing_submission_id) references writing_submissions (id) on delete set null,
    constraint fk_ai_feedbacks_speaking_submission foreign key (speaking_submission_id) references speaking_submissions (id) on delete set null,
    constraint chk_ai_feedbacks_type check (feedback_type in ('writing', 'speaking', 'study_plan')),
    constraint chk_ai_feedbacks_status check (status in ('queued', 'processing', 'completed', 'failed')),
    constraint chk_ai_feedbacks_tokens check (prompt_tokens >= 0 and completion_tokens >= 0),
    constraint chk_ai_feedbacks_cost_non_negative check (estimated_cost >= 0),
    constraint chk_ai_feedbacks_overall_band check (overall_band is null or (overall_band >= 0 and overall_band <= 9)),
    constraint chk_ai_feedbacks_completed_at check (completed_at is null or completed_at >= created_at),
    constraint chk_ai_feedbacks_submission_shape check (
        (feedback_type = 'writing' and writing_submission_id is not null and speaking_submission_id is null)
        or (feedback_type = 'speaking' and speaking_submission_id is not null and writing_submission_id is null)
        or (feedback_type = 'study_plan' and writing_submission_id is null and speaking_submission_id is null)
    )
);

create table ai_usage_limits (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    period_start date not null,
    period_end date not null,
    free_requests_limit integer not null,
    used_requests integer not null default 0,
    hard_limit_requests integer,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_ai_usage_limits_user foreign key (user_id) references users (id) on delete cascade,
    constraint uq_ai_usage_limits_user_period unique (user_id, period_start, period_end),
    constraint chk_ai_usage_limits_period check (period_end >= period_start),
    constraint chk_ai_usage_limits_free_limit check (free_requests_limit >= 0),
    constraint chk_ai_usage_limits_used_requests check (used_requests >= 0),
    constraint chk_ai_usage_limits_hard_limit check (hard_limit_requests is null or hard_limit_requests >= free_requests_limit),
    constraint chk_ai_usage_limits_used_within_hard_limit check (hard_limit_requests is null or used_requests <= hard_limit_requests)
);

create table study_plans (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    target_band numeric(2,1) not null,
    current_band numeric(2,1),
    duration_days integer not null,
    weakest_skills jsonb,
    plan_summary jsonb not null,
    starts_at date not null,
    ends_at date not null,
    created_by_feedback_id bigint,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_study_plans_student_user foreign key (student_user_id) references users (id),
    constraint fk_study_plans_created_by_feedback foreign key (created_by_feedback_id) references ai_feedbacks (id) on delete set null,
    constraint chk_study_plans_target_band check (target_band >= 0 and target_band <= 9),
    constraint chk_study_plans_current_band check (current_band is null or (current_band >= 0 and current_band <= 9)),
    constraint chk_study_plans_duration check (duration_days > 0),
    constraint chk_study_plans_dates check (ends_at >= starts_at)
);

create table study_plan_tasks (
    id bigint generated by default as identity primary key,
    study_plan_id bigint not null,
    task_date date not null,
    title varchar(180) not null,
    description text,
    recommended_test_id bigint,
    recommended_listing_id bigint,
    completed_at timestamp with time zone,
    task_order integer not null,
    constraint fk_study_plan_tasks_study_plan foreign key (study_plan_id) references study_plans (id) on delete cascade,
    constraint fk_study_plan_tasks_recommended_test foreign key (recommended_test_id) references tests (id) on delete set null,
    constraint uq_study_plan_tasks_plan_date_order unique (study_plan_id, task_date, task_order),
    constraint chk_study_plan_tasks_order_positive check (task_order > 0)
);

create index idx_ai_feedbacks_status_created_at on ai_feedbacks (status, created_at);
create index idx_ai_feedbacks_student_type_created on ai_feedbacks (student_user_id, feedback_type, created_at);
create index idx_ai_feedbacks_writing_submission on ai_feedbacks (writing_submission_id);
create index idx_ai_feedbacks_speaking_submission on ai_feedbacks (speaking_submission_id);
create index idx_ai_usage_limits_user_period on ai_usage_limits (user_id, period_start, period_end);
create index idx_study_plans_student_created on study_plans (student_user_id, created_at);
create index idx_study_plan_tasks_date on study_plan_tasks (task_date);
create index idx_study_plan_tasks_recommended_test on study_plan_tasks (recommended_test_id);
