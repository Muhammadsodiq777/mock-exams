create table tests (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint,
    title varchar(180) not null,
    description text,
    type varchar(32) not null,
    difficulty varchar(40),
    estimated_band_min numeric(2,1),
    estimated_band_max numeric(2,1),
    duration_minutes integer not null,
    price_amount numeric(14,2) not null default 0,
    currency varchar(3) not null default 'UZS',
    is_free boolean not null default true,
    language varchar(20) not null default 'en',
    visibility varchar(24) not null default 'draft',
    moderation_note text,
    published_at timestamp with time zone,
    created_by_user_id bigint not null,
    reviewed_by_user_id bigint,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    deleted_at timestamp with time zone,
    constraint fk_tests_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id) on delete set null,
    constraint fk_tests_created_by_user foreign key (created_by_user_id) references users (id),
    constraint fk_tests_reviewed_by_user foreign key (reviewed_by_user_id) references users (id) on delete set null,
    constraint chk_tests_type check (
        type in (
            'listening',
            'reading',
            'writing_task_1',
            'writing_task_2',
            'speaking_part_1',
            'speaking_part_2',
            'speaking_part_3',
            'full_mock'
        )
    ),
    constraint chk_tests_visibility check (visibility in ('draft', 'submitted', 'published', 'rejected', 'archived')),
    constraint chk_tests_estimated_band_min check (estimated_band_min is null or (estimated_band_min >= 0 and estimated_band_min <= 9)),
    constraint chk_tests_estimated_band_max check (estimated_band_max is null or (estimated_band_max >= 0 and estimated_band_max <= 9)),
    constraint chk_tests_estimated_band_order check (
        estimated_band_min is null
        or estimated_band_max is null
        or estimated_band_min <= estimated_band_max
    ),
    constraint chk_tests_duration_positive check (duration_minutes > 0),
    constraint chk_tests_price_non_negative check (price_amount >= 0),
    constraint chk_tests_currency_length check (char_length(currency) = 3),
    constraint chk_tests_free_price check ((is_free = true and price_amount = 0) or is_free = false),
    constraint chk_tests_language_not_blank check (char_length(language) > 0)
);

create table test_tags (
    id bigint generated by default as identity primary key,
    name varchar(80) not null unique,
    slug varchar(100) not null unique
);

create table test_categories (
    id bigint generated by default as identity primary key,
    parent_id bigint,
    name varchar(100) not null,
    slug varchar(120) not null unique,
    sort_order integer not null default 0,
    is_active boolean not null default true,
    constraint fk_test_categories_parent foreign key (parent_id) references test_categories (id) on delete set null,
    constraint chk_test_categories_sort_order check (sort_order >= 0)
);

create table test_category_links (
    test_id bigint not null,
    category_id bigint not null,
    primary key (test_id, category_id),
    constraint fk_test_category_links_test foreign key (test_id) references tests (id) on delete cascade,
    constraint fk_test_category_links_category foreign key (category_id) references test_categories (id) on delete cascade
);

create table test_tag_links (
    test_id bigint not null,
    tag_id bigint not null,
    primary key (test_id, tag_id),
    constraint fk_test_tag_links_test foreign key (test_id) references tests (id) on delete cascade,
    constraint fk_test_tag_links_tag foreign key (tag_id) references test_tags (id) on delete cascade
);

create table test_sections (
    id bigint generated by default as identity primary key,
    test_id bigint not null,
    title varchar(180) not null,
    instructions text,
    passage_text text,
    audio_file_id bigint,
    section_order integer not null,
    duration_minutes integer,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_test_sections_test foreign key (test_id) references tests (id) on delete cascade,
    constraint fk_test_sections_audio_file foreign key (audio_file_id) references files (id) on delete set null,
    constraint uq_test_sections_test_order unique (test_id, section_order),
    constraint chk_test_sections_order_positive check (section_order > 0),
    constraint chk_test_sections_duration_positive check (duration_minutes is null or duration_minutes > 0)
);

create table reading_paragraphs (
    id bigint generated by default as identity primary key,
    section_id bigint not null,
    label varchar(20) not null,
    content text not null,
    paragraph_order integer not null,
    constraint fk_reading_paragraphs_section foreign key (section_id) references test_sections (id) on delete cascade,
    constraint uq_reading_paragraphs_section_label unique (section_id, label),
    constraint uq_reading_paragraphs_section_order unique (section_id, paragraph_order),
    constraint chk_reading_paragraphs_order_positive check (paragraph_order > 0)
);

create table listening_segments (
    id bigint generated by default as identity primary key,
    section_id bigint not null,
    title varchar(160),
    start_seconds integer not null,
    end_seconds integer not null,
    transcript text,
    segment_order integer not null,
    constraint fk_listening_segments_section foreign key (section_id) references test_sections (id) on delete cascade,
    constraint uq_listening_segments_section_order unique (section_id, segment_order),
    constraint chk_listening_segments_order_positive check (segment_order > 0),
    constraint chk_listening_segments_time_bounds check (start_seconds >= 0 and end_seconds > start_seconds)
);

create table questions (
    id bigint generated by default as identity primary key,
    section_id bigint not null,
    question_type varchar(40) not null,
    question_text text not null,
    instructions text,
    score numeric(6,2) not null default 1,
    question_order integer not null,
    related_paragraph_label varchar(20),
    listening_segment_id bigint,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_questions_section foreign key (section_id) references test_sections (id) on delete cascade,
    constraint fk_questions_listening_segment foreign key (listening_segment_id) references listening_segments (id) on delete set null,
    constraint uq_questions_section_order unique (section_id, question_order),
    constraint chk_questions_type check (
        question_type in (
            'multiple_choice',
            'true_false_not_given',
            'yes_no_not_given',
            'matching_headings',
            'matching_information',
            'sentence_completion',
            'summary_completion',
            'table_completion',
            'diagram_labeling',
            'short_answer',
            'gap_fill',
            'ordering',
            'essay_answer',
            'audio_answer'
        )
    ),
    constraint chk_questions_score_non_negative check (score >= 0),
    constraint chk_questions_order_positive check (question_order > 0)
);

create table question_options (
    id bigint generated by default as identity primary key,
    question_id bigint not null,
    option_label varchar(20) not null,
    option_text text not null,
    option_order integer not null,
    constraint fk_question_options_question foreign key (question_id) references questions (id) on delete cascade,
    constraint uq_question_options_id_question unique (id, question_id),
    constraint uq_question_options_question_label unique (question_id, option_label),
    constraint uq_question_options_question_order unique (question_id, option_order),
    constraint chk_question_options_order_positive check (option_order > 0)
);

create table question_answers (
    id bigint generated by default as identity primary key,
    question_id bigint not null,
    answer_value text not null,
    normalized_value text,
    is_primary boolean not null default true,
    answer_order integer not null default 1,
    explanation text,
    constraint fk_question_answers_question foreign key (question_id) references questions (id) on delete cascade,
    constraint chk_question_answers_order_positive check (answer_order > 0)
);

create index idx_tests_visibility_reviewed_at on tests (visibility, reviewed_at);
create index idx_tests_teacher_visibility on tests (teacher_profile_id, visibility);
create index idx_tests_created_by_user on tests (created_by_user_id, created_at);
create index idx_tests_type_difficulty on tests (type, difficulty);
create index idx_tests_published_at on tests (published_at);
create index idx_tests_deleted_at on tests (deleted_at);
create index idx_test_category_links_category on test_category_links (category_id);
create index idx_test_tag_links_tag on test_tag_links (tag_id);
create index idx_test_sections_audio_file on test_sections (audio_file_id);
create index idx_questions_type on questions (question_type);
create index idx_questions_listening_segment on questions (listening_segment_id);
