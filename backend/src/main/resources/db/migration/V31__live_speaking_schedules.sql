create table teacher_availability_blocks (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint not null,
    weekday integer not null,
    starts_at time not null,
    ends_at time not null,
    timezone varchar(80) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_teacher_availability_blocks_teacher
        foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint chk_teacher_availability_blocks_weekday check (weekday between 0 and 6),
    constraint chk_teacher_availability_blocks_window check (ends_at > starts_at)
);

create index idx_teacher_availability_blocks_teacher
    on teacher_availability_blocks (teacher_profile_id, weekday, starts_at);

create table speaking_session_slots (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint not null,
    starts_at timestamp with time zone not null,
    ends_at timestamp with time zone not null,
    timezone varchar(80) not null,
    price_amount numeric(14,2) not null,
    currency varchar(3) not null,
    capacity integer not null default 1,
    status varchar(24) not null,
    announced_at timestamp with time zone,
    reserved_until timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_speaking_session_slots_teacher
        foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint chk_speaking_session_slots_status
        check (status in ('draft', 'announced', 'reserved', 'booked', 'completed', 'cancelled')),
    constraint chk_speaking_session_slots_price check (price_amount >= 0),
    constraint chk_speaking_session_slots_currency check (char_length(currency) = 3),
    constraint chk_speaking_session_slots_window check (ends_at > starts_at),
    constraint chk_speaking_session_slots_capacity_one check (capacity = 1)
);

create index idx_speaking_session_slots_teacher_status_start
    on speaking_session_slots (teacher_profile_id, status, starts_at);
create index idx_speaking_session_slots_public_status_start
    on speaking_session_slots (status, starts_at);

create table speaking_session_bookings (
    id bigint generated by default as identity primary key,
    slot_id bigint not null,
    student_user_id bigint not null,
    teacher_profile_id bigint not null,
    payment_id bigint,
    status varchar(24) not null,
    price_amount numeric(14,2) not null,
    currency varchar(3) not null,
    hold_expires_at timestamp with time zone,
    booked_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    completed_at timestamp with time zone,
    no_show_at timestamp with time zone,
    meet_url varchar(500),
    calendar_event_id varchar(160),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_speaking_session_bookings_slot
        foreign key (slot_id) references speaking_session_slots (id) on delete cascade,
    constraint fk_speaking_session_bookings_student
        foreign key (student_user_id) references users (id) on delete cascade,
    constraint fk_speaking_session_bookings_teacher
        foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint fk_speaking_session_bookings_payment
        foreign key (payment_id) references payments (id) on delete set null,
    constraint chk_speaking_session_bookings_status
        check (status in ('reserved', 'booked', 'cancelled', 'expired', 'completed', 'no_show')),
    constraint chk_speaking_session_bookings_price check (price_amount >= 0),
    constraint chk_speaking_session_bookings_currency check (char_length(currency) = 3)
);

create index idx_speaking_session_bookings_student_status_created
    on speaking_session_bookings (student_user_id, status, created_at);
create index idx_speaking_session_bookings_teacher_status_start
    on speaking_session_bookings (teacher_profile_id, status, created_at);
create index idx_speaking_session_bookings_slot_status
    on speaking_session_bookings (slot_id, status);
create index idx_speaking_session_bookings_payment
    on speaking_session_bookings (payment_id);

alter table payments
    add constraint fk_payments_target_live_speaking_booking
    foreign key (target_live_speaking_booking_id) references speaking_session_bookings (id) on delete set null;

create index idx_payments_target_live_speaking_status
    on payments (target_live_speaking_booking_id, status, created_at);

create table google_calendar_connections (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint not null,
    provider varchar(40) not null,
    external_account_id varchar(160),
    calendar_id varchar(160),
    status varchar(24) not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_google_calendar_connections_teacher
        foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint uq_google_calendar_connections_teacher unique (teacher_profile_id),
    constraint chk_google_calendar_connections_status
        check (status in ('connected', 'disconnected', 'failed'))
);

create table google_calendar_sync_jobs (
    id bigint generated by default as identity primary key,
    booking_id bigint not null,
    teacher_profile_id bigint not null,
    provider varchar(40) not null,
    operation varchar(40) not null,
    status varchar(24) not null,
    provider_event_id varchar(160),
    meet_url varchar(500),
    failure_code varchar(80),
    failure_message varchar(500),
    attempts integer not null default 0,
    scheduled_at timestamp with time zone not null default current_timestamp,
    completed_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_google_calendar_sync_jobs_booking
        foreign key (booking_id) references speaking_session_bookings (id) on delete cascade,
    constraint fk_google_calendar_sync_jobs_teacher
        foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint chk_google_calendar_sync_jobs_status
        check (status in ('pending', 'completed', 'failed')),
    constraint chk_google_calendar_sync_jobs_operation
        check (operation in ('create_event', 'cancel_event'))
);

create index idx_google_calendar_sync_jobs_status_created
    on google_calendar_sync_jobs (status, created_at);
create index idx_google_calendar_sync_jobs_booking
    on google_calendar_sync_jobs (booking_id, created_at);
