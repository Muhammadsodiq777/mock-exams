create table student_streaks (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null unique,
    current_streak_days integer not null default 0,
    longest_streak_days integer not null default 0,
    last_activity_date date,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_student_streaks_student_user foreign key (student_user_id) references users (id) on delete cascade,
    constraint chk_student_streaks_current_non_negative check (current_streak_days >= 0),
    constraint chk_student_streaks_longest_non_negative check (longest_streak_days >= 0),
    constraint chk_student_streaks_longest_at_least_current check (longest_streak_days >= current_streak_days)
);

create table leaderboards (
    id bigint generated by default as identity primary key,
    period_key varchar(40) not null,
    skill varchar(40) not null,
    starts_at date not null,
    ends_at date not null,
    created_at timestamp with time zone not null default current_timestamp,
    constraint uq_leaderboards_period_skill unique (period_key, skill),
    constraint chk_leaderboards_dates check (ends_at >= starts_at)
);

create table leaderboard_entries (
    id bigint generated by default as identity primary key,
    leaderboard_id bigint not null,
    student_user_id bigint not null,
    rank integer not null,
    score numeric(8,2) not null,
    attempts_count integer not null default 0,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_leaderboard_entries_leaderboard foreign key (leaderboard_id) references leaderboards (id) on delete cascade,
    constraint fk_leaderboard_entries_student_user foreign key (student_user_id) references users (id) on delete cascade,
    constraint uq_leaderboard_entries_student unique (leaderboard_id, student_user_id),
    constraint uq_leaderboard_entries_rank unique (leaderboard_id, rank),
    constraint chk_leaderboard_entries_rank_positive check (rank > 0),
    constraint chk_leaderboard_entries_score_non_negative check (score >= 0),
    constraint chk_leaderboard_entries_attempts_non_negative check (attempts_count >= 0)
);

create table referral_codes (
    id bigint generated by default as identity primary key,
    owner_user_id bigint not null,
    code varchar(60) not null unique,
    reward_policy jsonb,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_referral_codes_owner_user foreign key (owner_user_id) references users (id) on delete cascade
);

create table referral_uses (
    id bigint generated by default as identity primary key,
    referral_code_id bigint not null,
    referred_user_id bigint not null unique,
    reward_granted_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_referral_uses_referral_code foreign key (referral_code_id) references referral_codes (id) on delete cascade,
    constraint fk_referral_uses_referred_user foreign key (referred_user_id) references users (id) on delete cascade,
    constraint chk_referral_uses_reward_granted_at check (reward_granted_at is null or reward_granted_at >= created_at)
);

create table school_accounts (
    id bigint generated by default as identity primary key,
    name varchar(180) not null,
    owner_user_id bigint not null,
    status varchar(24) not null default 'active',
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_school_accounts_owner_user foreign key (owner_user_id) references users (id),
    constraint chk_school_accounts_status check (status in ('active', 'suspended', 'banned', 'deleted'))
);

create table school_members (
    school_account_id bigint not null,
    user_id bigint not null,
    role varchar(24) not null,
    joined_at timestamp with time zone not null default current_timestamp,
    primary key (school_account_id, user_id),
    constraint fk_school_members_school_account foreign key (school_account_id) references school_accounts (id) on delete cascade,
    constraint fk_school_members_user foreign key (user_id) references users (id) on delete cascade,
    constraint chk_school_members_role check (role in ('owner', 'teacher', 'student', 'manager'))
);

create index idx_student_streaks_activity on student_streaks (last_activity_date);
create index idx_leaderboards_period_dates on leaderboards (period_key, starts_at, ends_at);
create index idx_leaderboard_entries_rank on leaderboard_entries (leaderboard_id, rank);
create index idx_leaderboard_entries_student on leaderboard_entries (student_user_id, updated_at);
create index idx_referral_codes_owner_active on referral_codes (owner_user_id, is_active);
create index idx_referral_uses_code_created on referral_uses (referral_code_id, created_at);
create index idx_school_accounts_owner_status on school_accounts (owner_user_id, status);
create index idx_school_members_user_role on school_members (user_id, role);
