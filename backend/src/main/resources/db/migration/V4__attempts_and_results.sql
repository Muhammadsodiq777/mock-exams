create table test_attempts (
    id bigint generated by default as identity primary key,
    test_id bigint not null,
    student_user_id bigint not null,
    status varchar(24) not null default 'in_progress',
    started_at timestamp with time zone not null default current_timestamp,
    submitted_at timestamp with time zone,
    expires_at timestamp with time zone,
    time_spent_seconds integer not null default 0,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_test_attempts_test foreign key (test_id) references tests (id),
    constraint fk_test_attempts_student_user foreign key (student_user_id) references users (id),
    constraint chk_test_attempts_status check (status in ('in_progress', 'submitted', 'expired', 'cancelled')),
    constraint chk_test_attempts_time_spent_non_negative check (time_spent_seconds >= 0),
    constraint chk_test_attempts_submitted_after_start check (submitted_at is null or submitted_at >= started_at),
    constraint chk_test_attempts_expires_after_start check (expires_at is null or expires_at > started_at)
);

create table student_answers (
    id bigint generated by default as identity primary key,
    attempt_id bigint not null,
    question_id bigint not null,
    answer_text text,
    selected_option_id bigint,
    audio_file_id bigint,
    is_correct boolean,
    score_awarded numeric(6,2),
    answered_at timestamp with time zone,
    constraint fk_student_answers_attempt foreign key (attempt_id) references test_attempts (id) on delete cascade,
    constraint fk_student_answers_question foreign key (question_id) references questions (id),
    constraint fk_student_answers_selected_option foreign key (selected_option_id) references question_options (id) on delete set null,
    constraint fk_student_answers_selected_option_question
        foreign key (selected_option_id, question_id) references question_options (id, question_id),
    constraint fk_student_answers_audio_file foreign key (audio_file_id) references files (id) on delete set null,
    constraint uq_student_answers_attempt_question unique (attempt_id, question_id),
    constraint chk_student_answers_score_non_negative check (score_awarded is null or score_awarded >= 0),
    constraint chk_student_answers_has_response check (
        answer_text is not null
        or selected_option_id is not null
        or audio_file_id is not null
    )
);

create table test_results (
    id bigint generated by default as identity primary key,
    attempt_id bigint not null unique,
    raw_score numeric(8,2) not null,
    max_score numeric(8,2) not null,
    estimated_band numeric(2,1),
    correct_count integer not null default 0,
    incorrect_count integer not null default 0,
    weak_question_types jsonb,
    summary jsonb,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_test_results_attempt foreign key (attempt_id) references test_attempts (id) on delete cascade,
    constraint chk_test_results_scores check (raw_score >= 0 and max_score > 0 and raw_score <= max_score),
    constraint chk_test_results_estimated_band check (estimated_band is null or (estimated_band >= 0 and estimated_band <= 9)),
    constraint chk_test_results_counts check (correct_count >= 0 and incorrect_count >= 0)
);

create table writing_submissions (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    test_attempt_id bigint,
    task_type varchar(32) not null,
    prompt text not null,
    answer_text text not null,
    word_count integer,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_writing_submissions_student_user foreign key (student_user_id) references users (id),
    constraint fk_writing_submissions_test_attempt foreign key (test_attempt_id) references test_attempts (id) on delete set null,
    constraint chk_writing_submissions_task_type check (task_type in ('writing_task_1', 'writing_task_2')),
    constraint chk_writing_submissions_word_count check (word_count is null or word_count >= 0)
);

create table speaking_submissions (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    test_attempt_id bigint,
    part_type varchar(32) not null,
    prompt text not null,
    audio_file_id bigint not null,
    transcript text,
    duration_seconds integer,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_speaking_submissions_student_user foreign key (student_user_id) references users (id),
    constraint fk_speaking_submissions_test_attempt foreign key (test_attempt_id) references test_attempts (id) on delete set null,
    constraint fk_speaking_submissions_audio_file foreign key (audio_file_id) references files (id),
    constraint chk_speaking_submissions_part_type check (part_type in ('speaking_part_1', 'speaking_part_2', 'speaking_part_3')),
    constraint chk_speaking_submissions_duration check (duration_seconds is null or duration_seconds > 0)
);

create index idx_test_attempts_student_status on test_attempts (student_user_id, status, started_at);
create index idx_test_attempts_test_status on test_attempts (test_id, status, started_at);
create index idx_test_attempts_submitted_at on test_attempts (submitted_at);
create index idx_student_answers_question on student_answers (question_id);
create index idx_student_answers_selected_option on student_answers (selected_option_id);
create index idx_test_results_created_at on test_results (created_at);
create index idx_writing_submissions_student_created on writing_submissions (student_user_id, created_at);
create index idx_writing_submissions_attempt on writing_submissions (test_attempt_id);
create index idx_speaking_submissions_student_created on speaking_submissions (student_user_id, created_at);
create index idx_speaking_submissions_attempt on speaking_submissions (test_attempt_id);
