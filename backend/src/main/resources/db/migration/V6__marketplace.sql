create table marketplace_listings (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint,
    test_id bigint,
    title varchar(180) not null,
    description text,
    listing_type varchar(40) not null,
    price_amount numeric(14,2) not null,
    currency varchar(3) not null default 'UZS',
    is_active boolean not null default false,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_marketplace_listings_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id) on delete set null,
    constraint fk_marketplace_listings_test foreign key (test_id) references tests (id) on delete set null,
    constraint chk_marketplace_listings_type check (
        listing_type in (
            'single_test',
            'test_pack',
            'writing_course',
            'speaking_question_pack',
            'vocabulary_pack',
            'full_mock_exam',
            'subscription_plan'
        )
    ),
    constraint chk_marketplace_listings_price_non_negative check (price_amount >= 0),
    constraint chk_marketplace_listings_currency_length check (char_length(currency) = 3)
);

create table marketplace_listing_items (
    id bigint generated by default as identity primary key,
    listing_id bigint not null,
    test_id bigint,
    file_id bigint,
    title varchar(180),
    description text,
    item_order integer not null,
    constraint fk_marketplace_listing_items_listing foreign key (listing_id) references marketplace_listings (id) on delete cascade,
    constraint fk_marketplace_listing_items_test foreign key (test_id) references tests (id) on delete set null,
    constraint fk_marketplace_listing_items_file foreign key (file_id) references files (id) on delete set null,
    constraint uq_marketplace_listing_items_order unique (listing_id, item_order),
    constraint chk_marketplace_listing_items_order_positive check (item_order > 0),
    constraint chk_marketplace_listing_items_reference check (test_id is not null or file_id is not null)
);

create table purchases (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    listing_id bigint not null,
    payment_id bigint,
    purchased_at timestamp with time zone not null default current_timestamp,
    access_expires_at timestamp with time zone,
    constraint fk_purchases_student_user foreign key (student_user_id) references users (id),
    constraint fk_purchases_listing foreign key (listing_id) references marketplace_listings (id),
    constraint uq_purchases_student_listing unique (student_user_id, listing_id),
    constraint chk_purchases_access_expires_after_purchase check (access_expires_at is null or access_expires_at > purchased_at)
);

create table subscriptions (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    listing_id bigint not null,
    payment_id bigint,
    status varchar(24) not null default 'active',
    starts_at timestamp with time zone not null,
    ends_at timestamp with time zone not null,
    cancelled_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_subscriptions_student_user foreign key (student_user_id) references users (id),
    constraint fk_subscriptions_listing foreign key (listing_id) references marketplace_listings (id),
    constraint chk_subscriptions_status check (status in ('active', 'cancelled', 'expired', 'past_due')),
    constraint chk_subscriptions_dates check (ends_at > starts_at),
    constraint chk_subscriptions_cancelled_at check (cancelled_at is null or cancelled_at >= starts_at)
);

create table reviews (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    teacher_profile_id bigint,
    test_id bigint,
    rating smallint not null,
    comment text,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_reviews_student_user foreign key (student_user_id) references users (id),
    constraint fk_reviews_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id) on delete set null,
    constraint fk_reviews_test foreign key (test_id) references tests (id) on delete set null,
    constraint uq_reviews_student_test unique (student_user_id, test_id),
    constraint uq_reviews_student_teacher unique (student_user_id, teacher_profile_id),
    constraint chk_reviews_rating check (rating between 1 and 5),
    constraint chk_reviews_target check (
        (teacher_profile_id is not null and test_id is null)
        or (teacher_profile_id is null and test_id is not null)
    )
);

alter table study_plan_tasks
    add constraint fk_study_plan_tasks_recommended_listing
    foreign key (recommended_listing_id) references marketplace_listings (id) on delete set null;

create index idx_marketplace_listings_active_type on marketplace_listings (is_active, listing_type);
create index idx_marketplace_listings_teacher on marketplace_listings (teacher_profile_id, is_active);
create index idx_marketplace_listings_test on marketplace_listings (test_id);
create index idx_marketplace_listing_items_test on marketplace_listing_items (test_id);
create index idx_marketplace_listing_items_file on marketplace_listing_items (file_id);
create index idx_purchases_student_purchased_at on purchases (student_user_id, purchased_at);
create index idx_purchases_listing_purchased_at on purchases (listing_id, purchased_at);
create index idx_purchases_access_expires_at on purchases (access_expires_at);
create index idx_subscriptions_student_status on subscriptions (student_user_id, status, ends_at);
create index idx_subscriptions_listing_status on subscriptions (listing_id, status);
create index idx_reviews_teacher_created on reviews (teacher_profile_id, created_at);
create index idx_reviews_test_created on reviews (test_id, created_at);
create index idx_study_plan_tasks_recommended_listing on study_plan_tasks (recommended_listing_id);
