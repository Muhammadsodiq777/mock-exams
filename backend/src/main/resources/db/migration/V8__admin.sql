create table complaints (
    id bigint generated by default as identity primary key,
    submitted_by_user_id bigint not null,
    target_user_id bigint,
    target_teacher_profile_id bigint,
    target_test_id bigint,
    status varchar(24) not null default 'open',
    reason varchar(160) not null,
    description text,
    resolution_note text,
    reviewed_by_user_id bigint,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_complaints_submitted_by_user foreign key (submitted_by_user_id) references users (id),
    constraint fk_complaints_target_user foreign key (target_user_id) references users (id) on delete set null,
    constraint fk_complaints_target_teacher_profile foreign key (target_teacher_profile_id) references teacher_profiles (id) on delete set null,
    constraint fk_complaints_target_test foreign key (target_test_id) references tests (id) on delete set null,
    constraint fk_complaints_reviewed_by_user foreign key (reviewed_by_user_id) references users (id) on delete set null,
    constraint chk_complaints_status check (status in ('open', 'under_review', 'resolved', 'rejected')),
    constraint chk_complaints_target check (
        target_user_id is not null
        or target_teacher_profile_id is not null
        or target_test_id is not null
    ),
    constraint chk_complaints_reviewed_at check (reviewed_at is null or reviewed_at >= created_at)
);

create table notifications (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    type varchar(32) not null,
    title varchar(160) not null,
    body text not null,
    payload jsonb,
    read_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_notifications_user foreign key (user_id) references users (id) on delete cascade,
    constraint chk_notifications_type check (type in ('system', 'test_moderation', 'payment', 'withdrawal', 'ai_feedback')),
    constraint chk_notifications_read_at check (read_at is null or read_at >= created_at)
);

create table banners (
    id bigint generated by default as identity primary key,
    title varchar(160) not null,
    image_file_id bigint,
    target_url varchar(500),
    placement varchar(80) not null,
    status varchar(24) not null default 'draft',
    starts_at timestamp with time zone,
    ends_at timestamp with time zone,
    created_by_user_id bigint not null,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_banners_image_file foreign key (image_file_id) references files (id) on delete set null,
    constraint fk_banners_created_by_user foreign key (created_by_user_id) references users (id),
    constraint chk_banners_status check (status in ('draft', 'scheduled', 'active', 'paused', 'expired')),
    constraint chk_banners_dates check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create table platform_settings (
    id bigint generated by default as identity primary key,
    setting_key varchar(120) not null unique,
    setting_value jsonb not null,
    updated_by_user_id bigint,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_platform_settings_updated_by_user foreign key (updated_by_user_id) references users (id) on delete set null
);

create index idx_complaints_status_created on complaints (status, created_at);
create index idx_complaints_target_user on complaints (target_user_id, status);
create index idx_complaints_target_teacher on complaints (target_teacher_profile_id, status);
create index idx_complaints_target_test on complaints (target_test_id, status);
create index idx_notifications_user_read_created on notifications (user_id, read_at, created_at);
create index idx_notifications_type_created on notifications (type, created_at);
create index idx_banners_status_placement on banners (status, placement);
create index idx_banners_schedule on banners (starts_at, ends_at);

