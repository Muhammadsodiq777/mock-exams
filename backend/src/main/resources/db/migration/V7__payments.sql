create table payments (
    id bigint generated by default as identity primary key,
    student_user_id bigint not null,
    provider varchar(80) not null,
    provider_payment_id varchar(160),
    status varchar(24) not null default 'pending',
    amount numeric(14,2) not null,
    currency varchar(3) not null default 'UZS',
    metadata jsonb,
    created_at timestamp with time zone not null default current_timestamp,
    paid_at timestamp with time zone,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_payments_student_user foreign key (student_user_id) references users (id),
    constraint chk_payments_status check (status in ('pending', 'paid', 'failed', 'cancelled', 'refunded')),
    constraint chk_payments_amount_non_negative check (amount >= 0),
    constraint chk_payments_currency_length check (char_length(currency) = 3),
    constraint chk_payments_paid_at check (paid_at is null or paid_at >= created_at)
);

create table payment_disputes (
    id bigint generated by default as identity primary key,
    payment_id bigint not null,
    opened_by_user_id bigint not null,
    status varchar(24) not null default 'open',
    reason varchar(160) not null,
    description text,
    resolution_note text,
    reviewed_by_user_id bigint,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_payment_disputes_payment foreign key (payment_id) references payments (id) on delete cascade,
    constraint fk_payment_disputes_opened_by_user foreign key (opened_by_user_id) references users (id),
    constraint fk_payment_disputes_reviewed_by_user foreign key (reviewed_by_user_id) references users (id) on delete set null,
    constraint chk_payment_disputes_status check (status in ('open', 'under_review', 'refunded', 'rejected', 'resolved')),
    constraint chk_payment_disputes_reviewed_at check (reviewed_at is null or reviewed_at >= created_at)
);

create table teacher_wallets (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint not null unique,
    balance_amount numeric(14,2) not null default 0,
    pending_amount numeric(14,2) not null default 0,
    currency varchar(3) not null default 'UZS',
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_teacher_wallets_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id) on delete cascade,
    constraint chk_teacher_wallets_balance_non_negative check (balance_amount >= 0),
    constraint chk_teacher_wallets_pending_non_negative check (pending_amount >= 0),
    constraint chk_teacher_wallets_currency_length check (char_length(currency) = 3)
);

create table withdrawal_requests (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint not null,
    requested_amount numeric(14,2) not null,
    currency varchar(3) not null default 'UZS',
    status varchar(24) not null default 'requested',
    payout_details jsonb not null,
    reviewed_by_user_id bigint,
    reviewed_at timestamp with time zone,
    rejection_reason text,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_withdrawal_requests_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id),
    constraint fk_withdrawal_requests_reviewed_by_user foreign key (reviewed_by_user_id) references users (id) on delete set null,
    constraint chk_withdrawal_requests_status check (status in ('requested', 'approved', 'rejected', 'paid', 'cancelled')),
    constraint chk_withdrawal_requests_amount_positive check (requested_amount > 0),
    constraint chk_withdrawal_requests_currency_length check (char_length(currency) = 3),
    constraint chk_withdrawal_requests_reviewed_at check (reviewed_at is null or reviewed_at >= created_at)
);

create table teacher_transactions (
    id bigint generated by default as identity primary key,
    wallet_id bigint not null,
    purchase_id bigint,
    withdrawal_request_id bigint,
    transaction_type varchar(24) not null,
    gross_amount numeric(14,2) not null,
    platform_commission_amount numeric(14,2) not null default 0,
    net_amount numeric(14,2) not null,
    currency varchar(3) not null default 'UZS',
    description varchar(255),
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_teacher_transactions_wallet foreign key (wallet_id) references teacher_wallets (id) on delete cascade,
    constraint fk_teacher_transactions_purchase foreign key (purchase_id) references purchases (id) on delete set null,
    constraint fk_teacher_transactions_withdrawal_request foreign key (withdrawal_request_id) references withdrawal_requests (id) on delete set null,
    constraint chk_teacher_transactions_type check (transaction_type in ('earning', 'commission', 'withdrawal', 'refund', 'adjustment')),
    constraint chk_teacher_transactions_amounts check (
        gross_amount >= 0
        and platform_commission_amount >= 0
        and net_amount >= 0
        and platform_commission_amount <= gross_amount
    ),
    constraint chk_teacher_transactions_currency_length check (char_length(currency) = 3)
);

create table promo_codes (
    id bigint generated by default as identity primary key,
    teacher_profile_id bigint,
    code varchar(60) not null unique,
    discount_percent numeric(5,2),
    discount_amount numeric(14,2),
    currency varchar(3) default 'UZS',
    starts_at timestamp with time zone,
    expires_at timestamp with time zone,
    usage_limit integer,
    used_count integer not null default 0,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp,
    constraint fk_promo_codes_teacher_profile foreign key (teacher_profile_id) references teacher_profiles (id) on delete set null,
    constraint chk_promo_codes_discount_percent check (discount_percent is null or (discount_percent > 0 and discount_percent <= 100)),
    constraint chk_promo_codes_discount_amount check (discount_amount is null or discount_amount > 0),
    constraint chk_promo_codes_discount_shape check (discount_percent is not null or discount_amount is not null),
    constraint chk_promo_codes_currency_length check (currency is null or char_length(currency) = 3),
    constraint chk_promo_codes_dates check (expires_at is null or starts_at is null or expires_at > starts_at),
    constraint chk_promo_codes_usage_limit check (usage_limit is null or usage_limit > 0),
    constraint chk_promo_codes_used_count check (used_count >= 0),
    constraint chk_promo_codes_used_within_limit check (usage_limit is null or used_count <= usage_limit)
);

create table promo_code_redemptions (
    id bigint generated by default as identity primary key,
    promo_code_id bigint not null,
    student_user_id bigint not null,
    purchase_id bigint,
    payment_id bigint,
    discount_amount numeric(14,2) not null,
    currency varchar(3) not null default 'UZS',
    redeemed_at timestamp with time zone not null default current_timestamp,
    constraint fk_promo_code_redemptions_promo_code foreign key (promo_code_id) references promo_codes (id) on delete cascade,
    constraint fk_promo_code_redemptions_student_user foreign key (student_user_id) references users (id),
    constraint fk_promo_code_redemptions_purchase foreign key (purchase_id) references purchases (id) on delete set null,
    constraint fk_promo_code_redemptions_payment foreign key (payment_id) references payments (id) on delete set null,
    constraint uq_promo_code_redemptions_code_student_purchase unique (promo_code_id, student_user_id, purchase_id),
    constraint chk_promo_code_redemptions_discount_non_negative check (discount_amount >= 0),
    constraint chk_promo_code_redemptions_currency_length check (char_length(currency) = 3)
);

alter table purchases
    add constraint fk_purchases_payment
    foreign key (payment_id) references payments (id) on delete set null;

alter table subscriptions
    add constraint fk_subscriptions_payment
    foreign key (payment_id) references payments (id) on delete set null;

