create table band_conversions (
    id bigint generated by default as identity primary key,
    test_type varchar(32) not null,
    min_raw_score numeric(8,2) not null,
    max_raw_score numeric(8,2) not null,
    estimated_band numeric(2,1) not null,
    created_at timestamp with time zone not null default current_timestamp,
    constraint uq_band_conversions_range unique (test_type, min_raw_score, max_raw_score),
    constraint chk_band_conversions_test_type check (test_type in ('reading', 'listening')),
    constraint chk_band_conversions_raw_score_range check (
        min_raw_score >= 0
        and max_raw_score >= min_raw_score
    ),
    constraint chk_band_conversions_estimated_band check (estimated_band >= 0 and estimated_band <= 9)
);

